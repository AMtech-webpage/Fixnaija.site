import { createClient, SupabaseClient } from '@supabase/supabase-js';
import { UserProfile, UserRole } from '../types';

// Safely read Supabase environment variables without crashing if undefined
const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || 'https://mock-fixnaija.supabase.co';
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY || 'mock-anon-key-fixnaija-sample-development';

export const isSupabaseConfigured = (): boolean => {
  const url = import.meta.env.VITE_SUPABASE_URL;
  const key = import.meta.env.VITE_SUPABASE_ANON_KEY;
  return Boolean(
    url &&
    key &&
    url.startsWith('https://') &&
    !url.includes('mock-') &&
    key.length > 20
  );
};

// Global Supabase client instance
export const supabase: SupabaseClient = createClient(supabaseUrl, supabaseAnonKey, {
  auth: {
    // IMPORTANT: Supabase Auth is disabled per strict architecture specifications.
    // Firebase exclusively handles user authentication.
    persistSession: false,
    autoRefreshToken: false,
  },
});

/**
 * Sets the Authorization Bearer header on the Supabase client
 * using the verified Supabase-compatible JWT generated by the backend.
 */
export function setSupabaseCustomToken(token: string | null) {
  try {
    const client = supabase as any;
    if (client && client.rest) {
      if (token) {
        client.rest.headers = {
          ...client.rest.headers,
          Authorization: `Bearer ${token}`,
        };
      } else if (client.rest.headers) {
        delete client.rest.headers.Authorization;
      }
    }
  } catch {
    // Non-fatal header configuration fallback
  }
}

/**
 * Fetch profile by Firebase UID from Supabase
 */
export async function fetchProfileByFirebaseUid(firebaseUid: string): Promise<UserProfile | null> {
  if (!isSupabaseConfigured()) {
    // Local fallback
    const raw = localStorage.getItem(`fixnaija_profile_${firebaseUid}`);
    return raw ? JSON.parse(raw) : null;
  }

  try {
    const { data, error } = await supabase
      .from('profiles')
      .select('*')
      .eq('firebase_uid', firebaseUid)
      .maybeSingle();

    if (error) {
      console.warn('Supabase profile query warning:', error.message);
      return null;
    }

    if (data) {
      return {
        id: data.id,
        firebase_uid: data.firebase_uid,
        email: data.email,
        full_name: data.full_name,
        phone: data.phone,
        state: data.state,
        lga: data.lga,
        city: data.city,
        account_roles: data.account_roles || ['hirer'],
        roles: data.account_roles || ['hirer'],
        avatar_url: data.avatar_url,
        is_verified: data.is_verified,
        created_at: data.created_at,
        updated_at: data.updated_at,
      };
    }
  } catch (err) {
    console.warn('Error fetching profile from Supabase:', err);
  }
  return null;
}

/**
 * Sync profile with backend via secure Firebase ID token verification
 */
export async function syncProfileWithBackend(
  firebaseIdToken: string,
  profileData: {
    full_name: string;
    phone?: string;
    state?: string;
    lga?: string;
    city?: string;
    account_roles?: UserRole[];
    avatar_url?: string;
  }
): Promise<{ success: boolean; profile?: UserProfile; supabaseToken?: string; error?: string }> {
  try {
    const res = await fetch('/api/auth/verify-and-sync-profile', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${firebaseIdToken}`,
      },
      body: JSON.stringify(profileData),
    });

    const data = await res.json();
    if (!res.ok || !data.success) {
      return { success: false, error: data.error || 'Server profile synchronization failed.' };
    }

    if (data.supabaseToken) {
      setSupabaseCustomToken(data.supabaseToken);
    }

    // Cache locally for offline capability
    if (data.profile?.firebase_uid) {
      localStorage.setItem(`fixnaija_profile_${data.profile.firebase_uid}`, JSON.stringify(data.profile));
    }

    return {
      success: true,
      profile: data.profile,
      supabaseToken: data.supabaseToken,
    };
  } catch (err: any) {
    console.error('Backend sync error:', err);
    return { success: false, error: err.message || 'Network error syncing with FixNaija server.' };
  }
}

/**
 * Fetch current authenticated user's profile from server
 */
export async function fetchCurrentServerProfile(firebaseIdToken: string): Promise<UserProfile | null> {
  try {
    const res = await fetch('/api/auth/me', {
      headers: {
        Authorization: `Bearer ${firebaseIdToken}`,
      },
    });

    if (!res.ok) return null;
    const data = await res.json();
    if (data.supabaseToken) {
      setSupabaseCustomToken(data.supabaseToken);
    }
    return data.profile || null;
  } catch {
    return null;
  }
}

/**
 * Supabase Storage Helpers
 */
export async function uploadToSupabaseStorage(
  bucketName: 'avatars' | 'tutorials' | 'verification_docs',
  filePath: string,
  file: File | Blob
): Promise<{ publicUrl?: string; error?: string }> {
  if (!isSupabaseConfigured()) {
    // Return sample asset URL for local preview
    return { publicUrl: '/src/assets/images/generator_solar_repair_1794306643540.jpg' };
  }

  try {
    const { error: uploadError } = await supabase.storage
      .from(bucketName)
      .upload(filePath, file, { upsert: true });

    if (uploadError) {
      return { error: uploadError.message };
    }

    const { data } = supabase.storage.from(bucketName).getPublicUrl(filePath);
    return { publicUrl: data.publicUrl };
  } catch (err: any) {
    return { error: err.message || 'Failed to upload file to Supabase storage.' };
  }
}
